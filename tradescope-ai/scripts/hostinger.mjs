/**
 * Hostinger VPS deployment helpers (pure — no network): the self-contained Compose file for Hostinger's Docker
 * Manager, the project environment, and the DNS records for the domain. Used by scripts/hostinger-deploy.mjs and
 * the "deploy to Hostinger" workflow; covered by tests/hostinger.test.ts.
 *
 * The Docker Manager receives only the Compose file (no repository checkout), so:
 * - the app image is built from the public GitHub repository at a pinned ref (BuildKit git context), and
 *   `pull_policy: build` makes every `up` build that ref instead of trying to pull a registry image;
 * - Caddy writes its Caddyfile from the command line (automatic HTTPS for the domain, www → apex);
 * - data lives in host folders under /opt/tradescope, never in Compose volumes, so replacing or deleting the
 *   project cannot remove it (and the VPS backups/snapshots include it).
 */
import { domainToASCII } from 'node:url';

export const DEFAULT_DOMAIN = 'trade.xn--3e0b707e'; // trade.한국
export const REPO_GIT = 'https://github.com/mrblackfree/mrts.git';
export const APP_DIR = 'tradescope-ai';
export const PROJECT = 'tradescope';
export const HOST_DIR = '/opt/tradescope';
export const HOSTINGER_API = 'https://developers.hostinger.com';

/** API base: Hostinger, or a loopback mock for tests — nothing else can redirect the token. */
export function apiBase(override) {
  return /^http:\/\/127\.0\.0\.1:\d+$/.test(String(override ?? '')) ? String(override) : HOSTINGER_API;
}

/** Server-side settings passed from the deploy environment to the app when set (values never printed). */
export const PASS_THROUGH = [
  'ADMIN_PASSWORD',
  'ADMIN_SECRET',
  'AI_API_KEY',
  'AI_BASE_URL',
  'AI_MODEL',
  'AI_DAILY_BUDGET',
  'AI_MAX_CALLS_PER_IP_PER_HOUR',
  'AI_DISABLED',
  'CONSULT_WEBHOOK_URL',
  'CONSULT_CONTACT_EMAIL',
  'DATA_GO_KR_SERVICE_KEY',
  'COMTRADE_API_KEY',
  'TRACK_SHIPSGO_TOKEN',
  'TRACK_SHIPSGO_DAILY_NEW',
  'TRACK_HLAG_CLIENT_ID',
  'TRACK_HLAG_CLIENT_SECRET',
  'TRACK_CMACGM_KEY',
  'UNIPASS_CARGO_KEY',
  'DATA_FEEDBACK_URL',
  'OVERRIDES_EDIT_URL',
];

/** Hostname in ASCII (punycode) form, or null. trade.한국 → trade.xn--3e0b707e */
export function asciiDomain(domain) {
  const d = domainToASCII(String(domain ?? '').trim().replace(/\.$/, '').toLowerCase());
  return d && /^[a-z0-9-]+(\.[a-z0-9-]+)+$/.test(d) ? d : null;
}

/** A git ref safe to put in a build-context URL: a commit SHA or a plain branch/tag name. */
export function validRef(ref) {
  const r = String(ref ?? '');
  return /^[0-9a-f]{7,40}$/.test(r) || (/^[A-Za-z0-9][A-Za-z0-9._/-]{0,99}$/.test(r) && !r.includes('..') && !r.endsWith('/') && !r.endsWith('.lock'));
}

/** Image tag for a ref: short SHA, or the branch name with unsafe characters replaced. */
export function imageTag(ref) {
  return /^[0-9a-f]{7,40}$/.test(ref) ? ref.slice(0, 12) : ref.replace(/[^A-Za-z0-9_.-]/g, '-').slice(0, 64);
}

/**
 * The Compose file. `envKeys` lists the settings the deploy passes (as ${KEY} from the project environment); a key
 * that is not passed is left out, so the app sees it unset rather than empty.
 */
export function renderCompose({ ref = 'main', domain = DEFAULT_DOMAIN, envKeys = ['ADMIN_PASSWORD', 'ADMIN_SECRET'] } = {}) {
  const host = asciiDomain(domain);
  if (!host) throw new Error(`invalid domain: ${domain}`);
  if (!validRef(ref)) throw new Error(`invalid git ref: ${ref}`);
  const keys = envKeys.filter((k) => PASS_THROUGH.includes(k));
  const env = keys.map((k) => `      ${k}: \${${k}}`).join('\n');
  return `# TradeScope AI on a Hostinger VPS — Docker Manager project "${PROJECT}" (generated by scripts/hostinger.mjs).
# Self-contained: the app is built from the public GitHub repository at ref "${ref}"; data stays in ${HOST_DIR}.
# Point the domain's A/AAAA records at the VPS and keep ports 80/443 open; Caddy gets the certificates.
name: ${PROJECT}
services:
  # gives the app user (uid 1001) its data folder on the host
  init-data:
    image: busybox:1.36
    command: ["sh", "-c", "mkdir -p /data && chown -R 1001:1001 /data && chmod 700 /data"]
    volumes:
      - ${HOST_DIR}/data:/data
    restart: "no"

  app:
    build:
      context: ${REPO_GIT}#${ref}:${APP_DIR}
      args:
        NEXT_PUBLIC_SITE_URL: https://${host}
    image: tradescope-ai:${imageTag(ref)}
    pull_policy: build
    restart: unless-stopped
    depends_on:
      init-data:
        condition: service_completed_successfully
    environment:
      NODE_ENV: production
      TRUST_PROXY: "1"
${env ? `${env}\n` : ''}    volumes:
      - ${HOST_DIR}/data:/app/.data
    expose:
      - "3000"

  caddy:
    image: caddy:2.8-alpine
    restart: unless-stopped
    depends_on:
      app:
        condition: service_healthy
    ports:
      - "80:80"
      - "443:443"
    entrypoint: ["/bin/sh", "-c"]
    command:
      - |
        cat > /etc/caddy/Caddyfile <<'CADDYFILE'
        ${host} {
            encode zstd gzip
            reverse_proxy app:3000
        }
        www.${host} {
            redir https://${host}{uri} permanent
        }
        CADDYFILE
        exec caddy run --config /etc/caddy/Caddyfile --adapter caddyfile
    volumes:
      - ${HOST_DIR}/caddy/data:/data
      - ${HOST_DIR}/caddy/config:/config
`;
}

/** Project environment (KEY=value lines) for the keys that are set. Throws on values Compose cannot carry. */
export function envFile(env) {
  const out = [];
  for (const k of PASS_THROUGH) {
    const v = env[k];
    if (v === undefined || v === null || String(v).trim() === '') continue;
    const s = String(v).trim();
    if (/[\r\n]/.test(s)) throw new Error(`${k}: value contains a line break`);
    if (s.includes('$')) throw new Error(`${k}: value contains "$", which Compose would interpolate`);
    out.push(`${k}=${s}`);
  }
  return out.join('\n');
}

/** Keys of envFile(env), in order. */
export function envKeys(env) {
  return PASS_THROUGH.filter((k) => env[k] !== undefined && env[k] !== null && String(env[k]).trim() !== '');
}

/** First IPv4 / IPv6 address of a Hostinger VirtualMachineResource. */
export function vmAddresses(vm) {
  const first = (list) => (Array.isArray(list) ? list.map((x) => x?.address).find(Boolean) : undefined);
  return { ipv4: first(vm?.ipv4) ?? null, ipv6: first(vm?.ipv6) ?? null };
}

/** DNS zone update: apex A (and AAAA when the VPS has IPv6) to the VPS, www → apex. */
export function dnsZone({ domain = DEFAULT_DOMAIN, ipv4, ipv6, ttl = 300 }) {
  const host = asciiDomain(domain);
  if (!host) throw new Error(`invalid domain: ${domain}`);
  if (!/^\d{1,3}(\.\d{1,3}){3}$/.test(String(ipv4 ?? ''))) throw new Error(`invalid IPv4: ${ipv4}`);
  const zone = [{ name: '@', type: 'A', ttl, records: [{ content: ipv4 }] }];
  if (ipv6) zone.push({ name: '@', type: 'AAAA', ttl, records: [{ content: ipv6 }] });
  zone.push({ name: 'www', type: 'CNAME', ttl, records: [{ content: `${host}.` }] });
  return { overwrite: true, zone };
}
